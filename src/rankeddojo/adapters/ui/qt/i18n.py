from __future__ import annotations

from collections.abc import Mapping

from PySide6.QtCore import QCoreApplication, QObject, QTranslator, Signal

DEFAULT_UI_LOCALE = "pt-BR"
SUPPORTED_UI_LOCALES: tuple[str, ...] = ("pt-BR", "en", "es")
LOCALE_LABELS: Mapping[str, str] = {
    "pt-BR": "Português (Brasil)",
    "en": "English",
    "es": "Español",
}


def normalize_ui_locale(locale: str | None) -> str:
    if locale in SUPPORTED_UI_LOCALES:
        return str(locale)
    return DEFAULT_UI_LOCALE


class CatalogTranslator(QTranslator):
    def __init__(self, locale: str, catalog: Mapping[str, Mapping[str, str]]) -> None:
        super().__init__()
        self._locale = normalize_ui_locale(locale)
        self._catalog = catalog

    def translate(
        self,
        context: str,
        source_text: str,
        disambiguation: str | None = None,
        n: int = -1,
    ) -> str:
        if self._locale == DEFAULT_UI_LOCALE:
            return source_text
        return self._catalog.get(self._locale, {}).get(source_text, source_text)


class LocaleService(QObject):
    locale_changed = Signal(str)

    def __init__(self, repository, app: QCoreApplication | None = None) -> None:
        super().__init__()
        self._repository = repository
        self._app = app or QCoreApplication.instance()
        self._translator: CatalogTranslator | None = None
        self._locale = normalize_ui_locale(self._load_saved_locale())
        self._install_translator()

    @property
    def locale(self) -> str:
        return self._locale

    def set_locale(self, locale: str) -> None:
        normalized = normalize_ui_locale(locale)
        if normalized == self._locale:
            self._save_locale(normalized)
            return
        self._locale = normalized
        self._save_locale(normalized)
        self._install_translator()
        self.locale_changed.emit(normalized)

    def translate(self, source_text: str, context: str = "RankedDojo") -> str:
        return QCoreApplication.translate(context, source_text)

    def _install_translator(self) -> None:
        if self._app is None:
            return
        if self._translator is not None:
            self._app.removeTranslator(self._translator)
        self._translator = CatalogTranslator(self._locale, TRANSLATIONS)
        self._app.installTranslator(self._translator)

    def _load_saved_locale(self) -> str | None:
        loader = getattr(self._repository, "load_ui_locale", None)
        return loader() if callable(loader) else None

    def _save_locale(self, locale: str) -> None:
        saver = getattr(self._repository, "save_ui_locale", None)
        if callable(saver):
            saver(locale)


def tr(source_text: str, context: str = "RankedDojo") -> str:
    return QCoreApplication.translate(context, source_text)


